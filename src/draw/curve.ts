// Ресемплинг штриха по сплайну Catmull-Rom — превращает редкие "сырые"
// точки указателя (pointermove срабатывает тем реже, чем быстрее движение)
// в плотную последовательность точек вдоль гладкой кривой между ними.
//
// render.ts рисует штрих как цепочку прямых отрезков между соседними
// точками — при малом числе точек на изгибе (например, при быстро
// нарисованной от руки окружности) это заметно как "гранёная" линия из
// нескольких прямых кусков вместо ровной кривой. Само render.ts трогать не
// нужно: если заранее насытить points() промежуточными точками так, чтобы
// расстояние между соседними точками было маленьким (единицы пикселей),
// та же самая логика отрисовки отрезками даёт визуально гладкую кривую.

import type { StrokePoint } from "../types";

function catmullRom(p0: number, p1: number, p2: number, p3: number, t: number): number {
  const t2 = t * t;
  const t3 = t2 * t;
  return (
    0.5 *
    (2 * p1 +
      (-p0 + p2) * t +
      (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 +
      (-p0 + 3 * p1 - 3 * p2 + p3) * t3)
  );
}

/**
 * Точка "перед первой"/"после последней", нужная сплайну для оценки
 * касательной на самих концах кривой. Если её взять равной самой крайней
 * точке (как при обычном clamp по границам массива), сплайн решает, что
 * скорость движения на конце штриха равна нулю — и когда штрих на самом
 * деле подходит к концу под углом (а не останавливается плавно), это
 * даёт видимый залом/крючок именно на кончике штриха. Особенно заметно,
 * когда штрих замыкается сам на себя (нарисовали окружность) — кончик
 * штриха физически рядом с его началом, и залом на кончике выглядит как
 * зазубрина прямо на видимой линии, а не теряется где-то в пустоте.
 * Линейная экстраполяция ("фантомная" точка по касательной последнего
 * отрезка) — стандартный приём для открытых Catmull-Rom сплайнов,
 * убирает это самозамыкание касательной на границах.
 */
function phantomBefore(p0: StrokePoint, p1: StrokePoint): StrokePoint {
  return {
    x: 2 * p0.x - p1.x,
    y: 2 * p0.y - p1.y,
    pressure: p0.pressure,
    tiltX: p0.tiltX,
    tiltY: p0.tiltY,
    t: p0.t,
  };
}

/**
 * Возвращает новый массив точек, где между каждой парой соседних исходных
 * точек вставлено столько промежуточных точек на сплайне Catmull-Rom,
 * чтобы шаг между ними был не больше STEP_PX — то есть кривая остаётся
 * гладкой независимо от того, насколько редко легли исходные точки.
 */
export function smoothStrokePoints(points: StrokePoint[]): StrokePoint[] {
  if (points.length < 3) return points;

  const STEP_PX = 2; // целевое расстояние между соседними точками результата
  const MAX_STEPS_PER_SPAN = 24; // защита от взрыва числа точек на очень длинных быстрых росчерках
  const last = points.length - 1;

  const out: StrokePoint[] = [points[0]];
  for (let i = 0; i < points.length - 1; i++) {
    const p1 = points[i];
    const p2 = points[i + 1];
    // На концах массива берём не дублированную крайнюю точку, а
    // экстраполированную "фантомную" — см. phantomBefore().
    const p0 = i === 0 ? phantomBefore(p1, p2) : points[i - 1];
    const p3 = i + 1 === last ? phantomBefore(p2, p1) : points[i + 2];

    const spanLen = Math.hypot(p2.x - p1.x, p2.y - p1.y);
    const steps = Math.max(1, Math.min(MAX_STEPS_PER_SPAN, Math.ceil(spanLen / STEP_PX)));

    for (let s = 1; s <= steps; s++) {
      const t = s / steps;
      out.push({
        x: catmullRom(p0.x, p1.x, p2.x, p3.x, t),
        y: catmullRom(p0.y, p1.y, p2.y, p3.y, t),
        pressure: catmullRom(p0.pressure, p1.pressure, p2.pressure, p3.pressure, t),
        tiltX: p2.tiltX,
        tiltY: p2.tiltY,
        t: p2.t,
      });
    }
  }
  return out;
}
